defmodule Mix.Tasks.Alva.Codegen do
  @shortdoc "Generates TypeScript bindings for LiveVue events"
  @moduledoc """
  Generates TypeScript bindings for LiveVue events defined in Ash resources.

  Reads the host application's configured `ash_domains`.
  Outputs generated files to `:alva, :output_dir` (defaults to `assets/js/alva`).
  """

  use Mix.Task

  @impl true
  def run(_args) do
    Mix.Task.run("compile")

    app = Mix.Project.config()[:app]
    output_dir = Application.get_env(:alva, :output_dir, "assets/js/alva")

    if Ash.Info.domains(app) == [] do
      Mix.shell().info(
        "No Ash domains found. Please configure config :#{app}, ash_domains: [...]"
      )
    else
      File.mkdir_p!(output_dir)

      events_map = Alva.Registry.event_map(app)
      signal_map = Alva.Registry.registry(app).signal_map

      resources =
        events_map
        |> Map.values()
        |> Enum.map(fn {resource, _event} -> resource end)
        |> Enum.uniq()

      generate_types_ts(resources, events_map, output_dir)
      generate_events_ts(events_map, output_dir)
      generate_signals_ts(signal_map, events_map, output_dir)
      generate_client_ts(events_map, output_dir)

      Mix.shell().info("Successfully generated TypeScript bindings in #{output_dir}")
    end
  end

  defp generate_types_ts(resources, events_map, output_dir) do
    content = Alva.Codegen.DtoGenerator.generate_types_ts(resources, events_map)
    write_file!(output_dir, "types.ts", content)
  end

  defp generate_events_ts(events_map, output_dir) do
    events_content =
      events_map
      |> Enum.map_join("\n", fn {event_name, {resource, event_def}} ->
        output_type = Alva.Codegen.DtoGenerator.output_type(resource, event_def)
        action = Ash.Resource.Info.action(resource, event_def.action)

        input_shape =
          Alva.Codegen.InputContract.generate_input_shape(
            resource,
            event_def,
            action,
            "            "
          )

        """
          "#{event_name}": {
            input: #{input_shape};
            output: AlvaResult<Types.#{output_type}>;
          };
        """
      end)

    content = """
    // This file is auto-generated by Alva.
    // Do not edit manually.

    import type { AlvaResult } from "./types";
    import type * as Types from "./types";

    export type AlvaEvents = {
    #{events_content}
    };
    """

    write_file!(output_dir, "events.ts", content)
  end

  defp generate_signals_ts(signal_map, events_map, output_dir) do
    subs_content =
      signal_map
      |> Enum.map_join("\n", fn {_key, {resource, signal_def}} ->
        payload_prop = generate_signal_payload_prop(signal_def, events_map, resource)

        """
          "#{signal_def.name}": {
            #{payload_prop}
          };
        """
      end)

    content = """
    // This file is auto-generated by Alva.
    // Do not edit manually.

    import type * as Types from "./types";

    export type AlvaSignals = {
    #{subs_content}
    };
    """

    write_file!(output_dir, "signals.ts", content)
  end

  defp generate_signal_payload_prop(_signal_def, _events_map, resource) do
    output_type = resource |> Module.split() |> List.last()
    "payload: Types.#{output_type};"
  end

  defp generate_client_ts(_events_map, output_dir) do
    content = """
    // This file is auto-generated by Alva.
    import type { AlvaEvents } from "./events";
    import { useAlvaApi } from "alva";

    export function createAlvaApi() {
      const base_api = useAlvaApi<AlvaEvents>();

      function create_deep_proxy(path: string[] = []): any {
        return new Proxy(() => {}, {
          get(target, prop: string) {
            if (path.length === 0 && prop === "call") {
              return base_api.call;
            }

            return create_deep_proxy([...path, prop]);
          },
          apply(target, thisArg, args) {
            const event = path.join(".");
            return base_api.call(event as keyof AlvaEvents, args[0], args[1]);
          }
        });
      }

      return create_deep_proxy();
    }

    export const ashCall = createAlvaApi().call;
    """

    write_file!(output_dir, "client.ts", content)
  end

  defp write_file!(output_dir, filename, content) do
    file_path = Path.join(output_dir, filename)
    File.write!(file_path, content)
  end
end
